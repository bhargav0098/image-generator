// Image helper: turns a Google Drive share link into a direct, embeddable image URL.
// Paste any ".../file/d/<ID>/view" link and it just works.
const driveImg = (shareUrl, width = 1600) => {
  const m = shareUrl.match(/\/d\/([\w-]+)/);
  return m ? `https://drive.google.com/thumbnail?id=${m[1]}&sz=w${width}` : shareUrl;
};

